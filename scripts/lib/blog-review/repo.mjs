/** Filesystem helpers for the blog review pipeline (repo layout aware). */
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export const POST_KEYS = [
  'slug', 'date', 'updated', 'topic', 'level', 'readingMinutes', 'title', 'description', 'excerpt',
  'keywords', 'sections', 'faq', 'sources', 'relatedTrack', 'relatedProductSlugs', 'relatedPostSlugs',
  'hubLinks', 'diagramSlugs', 'images',
];

/** @param {string} root */
export function reviewsDir(root) {
  return path.join(root, 'src/data/blogReviews');
}

/** @param {string} root @param {string} slug */
export function ledgerPath(root, slug) {
  return path.join(reviewsDir(root), `${slug}.claims.json`);
}

/** @param {string} root @param {string} slug */
export function reportPath(root, slug) {
  return path.join(reviewsDir(root), `${slug}.review.json`);
}

/** @param {string} root */
export function publishedSlugs(root) {
  const dir = path.join(root, 'src/data/blogPosts');
  const slugs = new Set();
  for (const f of readdirSync(dir)) {
    if (!f.endsWith('.ts')) continue;
    const m = readFileSync(path.join(dir, f), 'utf8').match(/slug:\s*['"]([^'"]+)['"]/);
    if (m) slugs.add(m[1]);
  }
  return slugs;
}

/**
 * @param {string} root
 * @param {{ today?: string, allowExistingSlug?: boolean }} [options]
 * @returns {import('./checks.mjs').CheckContext}
 */
export function buildCheckContext(root, options = {}) {
  const diagrams = JSON.parse(readFileSync(path.join(root, 'src/data/referenceDiagrams.data.json'), 'utf8'));
  const publicDir = path.join(root, 'public');
  const resolvePublic = (p) => {
    const full = path.resolve(publicDir, `.${p}`);
    return full.startsWith(publicDir + path.sep) ? full : null;
  };
  return {
    diagramSlugs: new Set(diagrams.map((d) => d.slug)),
    postSlugs: publishedSlugs(root),
    allowExistingSlug: Boolean(options.allowExistingSlug),
    today: options.today,
    fileSize(p) {
      const full = resolvePublic(p);
      try {
        return full ? statSync(full).size : null;
      } catch {
        return null;
      }
    },
    readText(p) {
      const full = resolvePublic(p);
      try {
        return full ? readFileSync(full, 'utf8') : null;
      } catch {
        return null;
      }
    },
  };
}

/**
 * Import a committed post by slug. Run node with --experimental-strip-types.
 * @param {string} root @param {string} slug
 */
export async function loadPostBySlug(root, slug) {
  const dir = path.join(root, 'src/data/blogPosts');
  for (const f of readdirSync(dir)) {
    if (!f.endsWith('.ts')) continue;
    const text = readFileSync(path.join(dir, f), 'utf8');
    if (!text.includes(`slug: '${slug}'`)) continue;
    const mod = await import(pathToFileURL(path.join(dir, f)).href);
    const post = Object.values(mod).find((v) => v && typeof v === 'object' && v.slug === slug);
    if (post) return { post, file: path.join(dir, f) };
  }
  return null;
}

/** @param {string} file */
export function readJsonIfExists(file) {
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

/** Keep only BlogPost fields, in a stable order. */
export function cleanPost(post) {
  const out = {};
  for (const key of POST_KEYS) if (post[key] !== undefined) out[key] = post[key];
  return out;
}

/** Serialize a value as TypeScript source in the repo's post style (single quotes, bare keys). */
export function toTsLiteral(value, indent = 0) {
  const pad = '  '.repeat(indent);
  const inner = '  '.repeat(indent + 1);
  if (value === null) return 'null';
  if (typeof value === 'string') {
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r/g, '\\r').replace(/\n/g, '\\n').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')}'`;
  }
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    return `[\n${value.map((v) => `${inner}${toTsLiteral(v, indent + 1)},`).join('\n')}\n${pad}]`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    if (!entries.length) return '{}';
    const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : toTsLiteral(k));
    return `{\n${entries.map(([k, v]) => `${inner}${key(k)}: ${toTsLiteral(v, indent + 1)},`).join('\n')}\n${pad}}`;
  }
  throw new Error(`cannot serialize ${typeof value}`);
}

/**
 * @param {any} post
 * @param {{ exportName: string, reportRel: string }} meta
 */
export function renderPostModule(post, meta) {
  return `import type { BlogPost } from '../blog';

/**
 * Generated by scripts/blog-auto.mjs and passed the automated review.
 * Review report: ${meta.reportRel}
 */
export const ${meta.exportName}: BlogPost = ${toTsLiteral(cleanPost(post))};
`;
}

/** @param {string} file @param {unknown} data */
export function writeJson(file, data) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
}
